import type { CollectionConfig } from 'payload'

/**
 * Orders - created by the checkout backend's Stripe webhook, not by hand. Only
 * fulfilment fields (status, tracking, notes) are editable in the admin;
 * everything captured at purchase time is read-only. Fully auth-gated (no
 * public read) since it holds customer PII.
 *
 * Mirrors the fields the original Laravel Order model carried so the Royal Mail
 * dispatch + tracking flow and Stripe reconciliation port across unchanged.
 */
export const Orders: CollectionConfig = {
  slug: 'orders',
  admin: {
    useAsTitle: 'orderRef',
    defaultColumns: ['orderRef', 'customerName', 'totalPence', 'fulfilmentStatus', 'createdAt'],
    group: 'Shop',
  },
  access: {
    read: ({ req }) => Boolean(req.user),
    create: ({ req }) => Boolean(req.user),
    update: ({ req }) => Boolean(req.user),
    delete: ({ req }) => Boolean(req.user),
  },
  timestamps: true,
  fields: [
    {
      name: 'orderRef',
      type: 'text',
      unique: true,
      index: true,
      admin: { readOnly: true, description: 'Generated by the checkout backend, e.g. CFG-20260730-4821.' },
    },
    {
      name: 'fulfilmentStatus',
      type: 'select',
      defaultValue: 'pending',
      options: [
        { label: 'Pending', value: 'pending' },
        { label: 'Paid', value: 'paid' },
        { label: 'Fulfilled', value: 'fulfilled' },
        { label: 'Shipped', value: 'shipped' },
        { label: 'Delivered', value: 'delivered' },
        { label: 'Needs attention', value: 'needs-attention' },
      ],
      admin: { description: 'Editable. Everything below is set by the shop and read-only.' },
    },
    { name: 'customerName', type: 'text', admin: { readOnly: true } },
    { name: 'customerEmail', type: 'email', admin: { readOnly: true } },
    {
      name: 'items',
      type: 'json',
      admin: { readOnly: true, description: 'Snapshot of purchased lines: name, size, sku, quantity, price (pence).' },
    },
    { name: 'subtotalPence', type: 'number', admin: { readOnly: true } },
    { name: 'shippingPence', type: 'number', admin: { readOnly: true } },
    { name: 'totalPence', type: 'number', admin: { readOnly: true } },
    { name: 'weightGrams', type: 'number', admin: { readOnly: true, description: 'Total parcel weight (grams), captured at checkout for Royal Mail dispatch.' } },
    {
      name: 'shippingAddress',
      type: 'group',
      admin: { readOnly: true },
      fields: [
        { name: 'line1', type: 'text' },
        { name: 'line2', type: 'text' },
        { name: 'city', type: 'text' },
        { name: 'county', type: 'text' },
        { name: 'postcode', type: 'text' },
      ],
    },
    { name: 'trackingNumber', type: 'text', admin: { description: 'Royal Mail tracking number (editable).' } },
    { name: 'trackingUrl', type: 'text', admin: { description: 'Full tracking link (editable).' } },
    { name: 'royalMailOrderId', type: 'text', admin: { readOnly: true } },
    { name: 'stripeSessionId', type: 'text', unique: true, index: true, admin: { readOnly: true } },
    { name: 'stripePaymentIntentId', type: 'text', admin: { readOnly: true } },
    { name: 'stripePaymentStatus', type: 'text', admin: { readOnly: true } },
    { name: 'notes', type: 'textarea', admin: { description: 'Internal notes (editable).' } },
    { name: 'shippedAt', type: 'date', admin: { readOnly: true } },
    { name: 'deliveredAt', type: 'date', admin: { readOnly: true } },
  ],
}
